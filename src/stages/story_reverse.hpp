#pragma once

// 从项目里已有的章节反推一份故事骨架。
//
// **老项目接不上新流程**，这是迁移里最后一条空着的路（见
// docs/故事优先重构方案.md 第六节）。老项目手里有的是一章章写好的剧本，
// 没有 story.json；于是人物关系、地点、全局记忆这些新做的东西它一样都用
// 不上，往下写第六章照样失忆。
//
// **这一步不碰大模型。** 反推出来的是骨架：章节表里的一条变成故事里的一
// 章，正文就是那一章的剧本原文，段落边界登记成候选位置。谁是谁、什么关系、
// 在哪儿，交给已经有的「读现成正文提结构」（stages/story_analyze）——那一步
// 才要模型。分成两步不是省事：骨架这一半是机械的、可重复的，混进模型调用
// 之后就没法说「重来一次得到的还是同一份」了。
//
// **整章照搬，边界一个都不动。** 老项目那几章已经排了分镜、出了片，章界要
// 是和章节表里现有的边界对不上，已经渲染好的镜头就落不回它该在的那一段了。
// 所以那张表是照着现有章节一比一列出来的：章节表一条对故事一章，整章。

#include "models/project.hpp"
#include "models/story.hpp"

namespace changji::stages {

/// 照着项目里已有的章节反推一份故事。
///
/// 只收**写了剧本**的那些：没剧本的反推出来是一章空正文，既提不出结构，
/// 章节计划那一条也是个空区间，只会在章节列表里占一行说不清的东西。
///
/// 章的顺序就是章节表的顺序，章 id 重新从 ch01 排——**不照搬 episode_id**。
/// 老项目里的 `episode_id` 可能是 ep01/ep03/ep07（删过几章），而章 id 要求
/// `^ch[0-9]+$` 且在故事里连续。章节计划那一条仍然指回真正的 episode_id，
/// 两边靠它对上。
models::Story story_from_episodes(const models::Project& project);

}  // namespace changji::stages
