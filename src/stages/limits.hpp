#pragma once

// 视频模型一次能生成多长、帧数要落在什么格子上。
//
// **单独一个头文件，因为四个阶段都要用它，而且必须是同一份。**
//
// 分镜要按它推时长档位，渲染要按它算帧数，配音要按它判一句台词能不能
// 装进一个镜头，装配要按它算每一镜在时间轴上真正占多久。之前
// storyboard.hpp 和 render.hpp 各写了一份 `kMaxFrames`——两份值碰巧一样，
// 所以一直没出事，但那是运气：任何一个文件同时包含这两个头就是重定义
// 错误，而只改一边则是"分镜按 5 秒排，渲染按 8 秒截"这种谁也发现不了的
// 不一致。
//
// ---
//
// **2026-09-13 从写死的常量改成配置项。** 原来这里写着
// `kMaxFrames = 121`，注释是「Wan 单段能生成的最大帧数……这是模型本身的
// 限制，不是可调参数」。两句话都对——**只是那个模型早就不用了**：服务器
// 2026-09-09 换成了 MiniMax-H3，而 H3 能出 5~15 秒，帧数的格子也不是
// Wan 的 4n+1 而是 17k+5（sd.cpp 的 docs/minimax_h3.md）。
//
// 于是同时错两头：
//
//   * 一章 60 秒被切成十几个 5 秒片段，而新模型本可以一镜十几秒——
//     切换碎、每镜都要单独出首帧和视频、台词被硬拆、镜间动作接不上；
//   * 我们按 4n+1 算帧数交给 sd.cpp，sd.cpp 再向上对齐到 17k+5，
//     **算出来比要的长**（4 秒档 97 帧 → 107 帧 = 4.458 秒），而装配的
//     时间轴按分镜表里那个名义值往前走，误差逐镜累积，字幕和画面越走越偏。
//
// 换模型只改得了 config.toml，改不到编译期常量——所以这几个数必须是配置。
// 换全精度、换卡、换模型，都只动配置，不重编。

#include <vector>

namespace changji::stages {

/// 视频模型一次能生成多长，以及帧数要对齐到什么格子上。
///
/// **结构体默认是最保守的那一档（Wan：121 帧 / 4n+1）**，不是当前在用的模型。
///
/// 这里是"什么都不知道"时的值：没跑 config::Runtime::replace（单元测试）、
/// 或者探测不到显卡。真正在用的那一份由 replace 按**模型能力 ∩ 这张卡跑得动**
/// 算出来注入，见 guess_video_limits / cap_by_vram。
///
/// 为什么默认保守而不是默认 H3：按短的排，最坏是浪费了新模型出长镜头的
/// 本事，片子照出；按长的排而这张卡其实跑不动，一镜跑几分钟然后 OOM，
/// 那一镜白跑。
struct VideoLimits {
    /// 单段最多多少帧。Wan 121；MiniMax-H3 按 15 秒 × 24fps 算 360。
    ///
    /// 上限不在格子上时，`frames_for` 往下取到不超过它的那个合法值
    /// （360 → 345 = 14.375 秒）。
    int max_frames = 121;
    /// 帧数的格子：合法帧数是 `step * k + base`。
    ///
    /// Wan 要 4n+1，MiniMax-H3 要 17k+5。**给错了不报错**——sd.cpp 会自己
    /// 向上对齐，而对齐到哪儿它不告诉你，表现是成片比分镜表长一点点。
    int frame_step = 4;
    int frame_base = 1;
    /// 画布的像素上限（宽 × 高）。0 = 不限。
    ///
    /// **超出去不是慢一点，是画面坏掉。** MiniMax-H3 的开源权重把画布钉在
    /// `canvas_max_pixels = 1032192`（= 1344 × 768，官方 diffusers 的
    /// MiniMaxH3Blocks 配置），短边 768；商业 API 那边主打的 2K（1440 短边）
    /// 靠的是一个叫 H3-Regenerate-2K 的模块，**不在开源发布里**。拿开源权重
    /// 直接出 2K 等于让它在训练分布之外跑，出来是伪影。
    ///
    /// 只用来**报警**，不用来悄悄降档：人选了 2K 却拿到标准档而且不吭声，
    /// 比出一条烂片更糟（config/settings.cpp 的 VideoConfig::size 注释里
    /// 特意写过这一条）。
    int max_pixels = 0;
    /// 这个模型**只认这一个帧率**时填它，0 = 不挑。
    ///
    /// MiniMax-H3 填 24：上游 `docs/minimax_h3.md` 写着「MiniMax-H3 runs at
    /// 24 fps; another requested value is overridden」，`stable-diffusion.cpp`
    /// 里也确实是硬改（`fps != 24` 就 `LOG_WARN` 然后赋 24）。
    ///
    /// **不认这一条的后果是全片变速，而不是报错。** 出来的裸帧是按 24fps
    /// 的节奏演的，我们却按 `[assembly].fps` 去编码和算时长：填 30 的话
    /// 每一镜都快 25%，人走路变小跑，配音对不上口型，字幕按 frames/30 排
    /// 也跟着偏。sd.cpp 那句 LOG_WARN 淹在一屏 CUDA Graph 日志里，没人看得见。
    ///
    /// Wan 留 0：sd.cpp 对它不做覆盖，我们传什么它用什么。
    int native_fps = 0;

    /// 这个秒数实际会生成多少帧：向上对齐到格子，再夹进上限。
    int frames_for(double duration_s, int fps = 24) const;

    /// 不超过 `max_frames` 的最大**合法**帧数（落在格子上的那个）。
    ///
    /// 上限本身常常不在格子上：MiniMax-H3 说能出 15 秒，15×24 = 360，
    /// 而 (360-5)/17 = 20.88。这时真正出得来的是 345 帧。
    int max_frames_on_grid() const;

    /// 单镜能生成的最长秒数。
    ///
    /// **分镜的时长档位必须由它推导，不能各写一份。** 早先档位表里有 8 秒
    /// 和 10 秒，而实际上限是 5 秒，多出来的部分被静默截断，成片比计划短了
    /// 一大截且没人发现。
    double max_duration_s(int fps = 24) const;

    /// 这一镜在时间轴上**真正**占多久（= frames_for 的结果 ÷ fps）。
    ///
    /// 装配要用它，不能用分镜表里那个名义值：名义 4 秒的镜头按 17k+5 对齐
    /// 之后是 4.458 秒，差的那 0.458 秒逐镜累积，字幕就从画面上漂走了。
    double real_duration_s(double duration_s, int fps = 24) const;

    /// 可选的时长档位（秒），升序。候选里 ≤ 上限的那些。
    std::vector<double> duration_slots(int fps = 24) const;
};

/// 按视频模型自己认它的限制。
///
/// **这三个数不该让人记着填。** 换模型时人改的是 `[models].video` 那一行，
/// 不会想起来还有帧数格子要跟着改；而填错了全程不报错——sd.cpp 自己把帧数
/// 向上对齐，表现只是成片比分镜表长一点点。所以按模型名认，配置里那三项
/// 只当覆盖用。
///
/// 认两处：
///   * 文件名里的模型名（`minimax_h3_fl2va-Q4_K_M.gguf` → H3）；
///   * 认不出时看编码器走哪条路——H3 用 `video_llm`（Qwen3-VL），
///     Wan 用 `video_text_encoder`（UMT5-XXL），配置里这两项只能填一个。
///
/// **两处都认不出就退回最保守的那一档（Wan）。** 宁可把镜头限短：按短的排，
/// 最坏是浪费了新模型出长镜头的本事，片子照出；按长的排而模型其实出不了，
/// 得到的是被静默截断的片子，而截在哪儿没人告诉你。
VideoLimits guess_video_limits(const std::string& video_model_file,
                               bool llm_encoder = false);

/// 按这张卡跑不跑得动，把模型的能力夹低。
///
/// **模型能出 15 秒不等于这张卡能出 15 秒。** 5090 32 GB 上 1280×704、
/// MiniMax-H3 权重全放内存时，一个五秒镜头的计算缓冲实测就要 ~14.6 GB
/// （跑到 51 段的第 46 段差 788 MB）——再长就 OOM，而 OOM 的代价是这一镜
/// 白跑几分钟。
///
/// ⚠️ **这是保守外推，不是实测出来的曲线。** 只有"五秒镜头要 14.6 GB"
/// 这一个锚点，按每帧线性摊（14.6 / 124 ≈ 0.118 GB/帧）再留三成余量。
/// 真实的显存曲线大概率不是线性的——sd.cpp 是分段跑的，峰值未必跟总帧数
/// 成正比。要放开长镜头之前**得拿这张卡实测一组**（同一镜跑 5 / 8 / 12 秒，
/// 量峰值显存），拿到数就把下面那个系数改掉。
///
/// vram_gb ≤ 0（探测不到显卡）时原样返回：什么都不知道就别自作主张放开。
VideoLimits cap_by_vram(VideoLimits limits, double vram_gb,
                        double resident_gb, int fps = 24);

/// 按画布把帧数夹到**内核跑得动**的范围。**这一条不是显存。**
///
/// 2026-09-13 在 5090 上照上面那段注释的要求量了一组（704×1280、H3
/// Q4_K_M、权重全放内存、Turbo 6 步，同一镜同一首帧）：
///
///   107 帧（4 秒）   峰值 28.8 GB   228 秒
///   192 帧（8 秒）   峰值 24.4 GB   485 秒
///   294 帧（12 秒）  **整个引擎当场死掉**，8 秒内：
///     `CUDA error: invalid configuration argument`（ggml_cuda_kernel_launch）
///
/// 两件事：显存曲线**根本不随帧数涨**——sd.cpp 按预算分段跑，长镜头换来
/// 的是时间（几乎线性）不是显存，所以 cap_by_vram 里那条「每帧 0.118 GB」
/// 是错的（只是错在保守那一侧）；而真正的墙是序列长到某个内核的启动网格
/// 超出 CUDA 的上限，报的不是 OOM，是启动参数非法，**炸的是整个进程**，
/// 正在跑的那一章全丢。cap_by_vram 在大卡上会把这个上限放开到 12 秒，
/// 然后正好撞上这堵墙。
///
/// 所以这一道按「像素 × 帧」量：704×1280×192 = 1.73 亿跑得动，
/// ×294 = 2.65 亿炸。天花板取跑得动的那个数（保守；真边界在两者之间，
/// 还没二分——每二分一次要炸一次引擎）。画布小，换算出来的帧数就多：
/// 544×928 下是 342 帧，比模型自己的上限还高，等于不夹；
/// 2K（1440×2560）下只剩 46 帧 ≈ 2 秒——2K 本来就跑不了（见 max_pixels）。
///
/// width / height ≤ 0（不知道画布）时原样返回。已经比天花板低的不会被抬高。
VideoLimits cap_by_kernel_limit(VideoLimits limits, int width, int height);

/// 进程内当前这一份。默认是最保守的那一档，由 config::Runtime::replace 注入。
///
/// 做成全局可设而不是到处传参：用到它的是 stages 里的纯函数
/// （snap_duration / frames_for / max_line_seconds），一路加参数会波及
/// 分镜、渲染、配音、装配几十个调用点，而这个值在一次运行里是不变的。
const VideoLimits& video_limits();
void set_video_limits(VideoLimits v);

/// 单个镜头能生成的最长时长。等于 `video_limits().max_duration_s(fps)`。
double max_shot_duration_s(int fps = 24);

/// 这一轮真正该用的帧率：模型挑帧率就听模型的，否则听配置的。
///
/// **拆成纯函数是为了能测**，也为了只有一处在做这个决定——帧率被四个
/// 地方读（渲染算帧数、装配算每镜时长、ffmpeg 编码、配音判一句装不装得下），
/// 在任何一处单独纠正都会让另外三处继续用旧值，而对不上的表现是画面
/// 和字幕慢慢错开，不是报错。
int effective_fps(const VideoLimits& limits, int configured_fps);

}  // namespace changji::stages
