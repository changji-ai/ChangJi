    /// 留下出片模型的原生音轨当环境声和动效。MiniMax-H3 每镜都出一条立体声，
    /// 以前在出片那步被 `-an` 丢掉了。**有没有台词都留**（用户 2026-09-14
    /// 定的）：有台词的镜头它压在台词底下，台词处再侧链压一道。
