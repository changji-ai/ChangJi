/// 剧本和分镜用的大模型。默认走本地 Ollama。
/// 画质档位的显式覆盖。
///
/// **默认全 0 = 用按显存推出来的那套**（见 models/hardware.cpp 的档位表）。
///
/// 这一节 2026-09-10 加的。以前档位只能通过 `POST /api/settings` 改，而且
/// **有意不写回文件**——当时的理由是"档位是按显存推的，写死等于把这台机器
/// 的显存刻进配置"。那个理由站不住：`[models]` 里全是这台机器的模型路径，
/// 这个文件本来就是机器专属的。真实后果是**设完重启就丢**：用户把成片档
/// 调成 1280×704 跑了一章，重启之后回到 960×544，而界面上没有任何提示。
///
/// 填了就以填的为准，没填的项照旧按显存推。
/// 这部电影的画面规格。**放在项目目录的 changji.toml 里**，一部电影一份。
///
/// 用户要决定的是"竖屏还是横屏、720p 还是 2K"，不是"1280 还是 1440"。
/// 宽高由这两项算出来（`models::VideoSpec::size()`），中间那层换算不该
/// 甩给用户——填错一个不是 32 倍数的数，报错要到出图那一步才出现。
///
/// **为什么在项目上而不是全局**：一台机器上可以同时有一部横屏的正片和一批
/// 竖版的物料（竖屏预告、花絮），画幅是这部电影的属性，不是这台机器的属性。
/// 全局那份 `[tiers]` 还在，作为没配项目时的回落。
struct VideoConfig {
    /// landscape（默认，16:9）/ portrait
    ///
    /// ⚠️ **这个默认只回答"盘上一个字都没说"的目录。** 项目自己的
    /// changji.toml 没写 orientation 时，`load_settings` 先从它的
    /// assets.json 把画幅推回来，剩下两种才落到这儿：目录里连 assets.json
    /// 都没有，或者那份比例在、是字符串、却既不是 16:9 也不是 9:16。
    /// **文件读不出来不算**——那一支按竖屏算，理由在
    /// `orientation_from_assets`。2026-09-18 这个默认
    /// 从 portrait 翻成 landscape，没有那条推导的话，翻的不只是新项目——
    /// 原委和撞出来的三件事写在 settings.cpp 的 `orientation_from_assets`。
    std::string orientation = "landscape";
    /// 720p / 2k
    std::string quality = "720p";

    /// 单个镜头最长几秒。**0 = 按模型和这张卡自己定**（老项目、全局默认）。
    ///
    /// **这是一部电影的属性，不是显存的函数。** 2026-09-13 实测
    /// （见 stages::cap_by_kernel_limit 头上那张表）：H3 权重全放内存时
    /// 峰值显存根本不随帧数涨，「按显存推单镜上限」推的是个不存在的量。
    /// 所以上限该由这部电影自己定。
    ///
    /// **这一行只管机器和这部电影允许多长，不替内容做决定**——一镜只演
    /// 一件事由提示词那两句原话管着：分镜那头的「一镜只演一件事」、剧本
    /// 那头的「每一拍只写一件事」。新建项目的模板里写的是 15.0；那个数
    /// 怎么从 5.0 改上来的、原来那条「8 秒会中途硬切」的实测后来查出是
    /// 别的病，都记在 settings.cpp 的 kProjectToml 那段注释里，这儿不再
    /// 抄一遍。
    ///
    /// 填了就和模型上限、显存上限、内核上限一起取最小；填不到的秒数
    /// 不会报错，只是分镜的时长档位里没有它。
    double max_shot_s = 0.0;

    /// 关键镜头**第一条不干净时**最多出几条换种子挑最好的（1..4，1 = 不多出）。
    ///
    /// 行业做法：10～15% 的镜头会漂，关键镜多出 20～30% 挑。哪些算关键
    /// 见 stages::is_hero_shot（开场钩子、章尾留扣、反转，加上第一镜和
    /// 最后一镜）。挑的依据是闸门量出来的数（过没过、运动量、有没有
    /// 片中硬切），见 stages::pick_take。第一条就过了闸门、运动量正常的
    /// 不再多出（stages::take_good_enough）——无条件出两条是整章翻倍。
    int hero_takes = 2;
    /// 连续动作的两镜，拿上一镜真出来的最后一帧当下一镜的首帧。
    /// 只对分镜里标了 `continuous_with_prev` 的镜头生效。
    bool chain_frames = true;

    std::vector<std::string> validate() const;

    /// 算出宽高。两边都是 32 的倍数。
    std::pair<int, int> size() const;

    /// 这部电影的画面比例。**画幅是唯一的源，比例是它的函数。**
    ///
    /// 以前 `StyleProfile.aspect_ratio` 是一份独立可改的拷贝，于是能配成
    /// 「横屏 + 9:16」——不报错，出来是参考图竖的、成片横的，而参考图正是
    /// 每一镜的底子。现在凡是要比例的地方都从这儿取（或者取那份由这儿
    /// 派生出来的拷贝，见 StyleProfile::aspect_ratio）。
    std::string aspect_ratio() const {
        return orientation == "landscape" ? "16:9" : "9:16";
    }
};

/// 「只做前 n 分钟」那个 n。**这部电影的属性**，跟着项目目录走。
///
/// 两处按钮读的是同一个值：分镜页那颗「只做前 N 分钟」、项目页那颗「一键
/// 成片」。各存一份的话，人在一处改完到另一处按，做出来的长度不是他刚填的
/// 那个——而两处都不会报错。
struct PreviewConfig {
    /// 前多少秒。**默认一分钟**：这一条的用处是"先看一眼这部片子长什么样"，
    /// 一分钟就看得出调子、画风、配音对不对，而每多一分钟就是多十几分钟的
    /// 显卡时间。要长的人自己往上调。
    double seconds = 60.0;

    std::vector<std::string> validate() const;
};

/// 比例反推画幅：`VideoConfig::aspect_ratio()` 的逆。认得出来才回值。
///
/// 没写 `[video]` 的老项目，画幅在盘上的记录是 assets.json 里那份比例
/// （见 settings.cpp 的 `orientation_from_assets`），把它推回画幅就是这张
/// 表反着查。**实现照着正向那个函数比，不另写一份映射**——另写一份的话，
/// 哪天加一档（比如 1:1）两边各改各的就会分家，而分家的表现是"这个项目
/// 读出来的画幅和它自己的参考图对不上"，全程不报错。
std::optional<std::string> orientation_of_aspect(const std::string& aspect_ratio);

