    ///     云上等于白拿回这些显存和每次驱逐/重载的时间。
    ///   * **写得好不好**。EQ-Bench 长文创作榜上（2026-09-13 抓的）
    ///     本机跑得动的那一档最高 59.0（Qwen3.5-27B），而云上的
    ///     GLM-5.3 是 81.8、DeepSeek-V4-Pro 75.6。这个跨度不是提示词
    ///     能补回来的。
    ///   * **钱**。默认那个 `glm-4.7-flash` 不要钱（还是要一把自己的
    ///     密钥，见 `api_key`）。退一步就算用收费的，一部 11 章的电影按
    ///     输入 20 万 / 输出 15 万 token 估，glm-5.3-flash 四毛，
    ///     写作榜 81.8 的 glm-5.3 也就五块。
    ///
    /// **2026-09-19 `local` 回来了**（进程内 llama.cpp，权重在 `[models].llm`）。
    /// 上面那三笔账 2026-09-14 让它被整个删掉；改主意的原因只有一条：这是
    /// 产品，要给别人用——图片、视频、配音全在本地，编剧不该是唯一要人自己
    /// 去申请密钥、自己撞 429 的一环。默认那档得是装上就能跑的。
    ///
    /// 回来的这一版和当年不一样：**没有语法层了**。schema 和远端一样当文字
    /// 贴在提示词后面、回来之后本地校验；思考自由流，按 `<think>` 拆开
    /// （infer/think_split.hpp）。当年"思考和语法冲突"的死结不存在了。
    /// 显存那笔账还在：它和出图出片抢同一张卡，归调度器管，出片要显存时
    /// 先卸它（llm::register_llm_slot）。写得好不好那笔账也还在——本地
    /// 那档最高 59 分对云上 81.8，所以远端仍然是「想写得更好」的升级项。
    ///
    /// 三个值：`remote`（打 API）、`local`（进程内）、`command`（本机命令行）。
    std::string backend = "remote";

    /// ---- `backend = "command"`：把本机装着的大模型命令行当后端 ----
    ///
    /// 用户 2026-09-18：「增加对 claudecode 和 codex 命令版的支持」。
    ///
    /// **为什么值得单开一条路。** 那两个命令行是按**订阅**算钱的（Claude
    /// 的 Pro/Max、Codex 的 ChatGPT 套餐），而 API 是按 token 算。这条
    /// 流水线最费的就是文字：一部电影几十万 token。手上已经有订阅的人，走
    /// 命令行等于这部分不再额外花钱。
    ///
    /// **不硬编那两个名字。** 这里是一个通用的"跑个命令"后端：`command`
    /// 是可执行文件，`command_args` 是参数。理由有两条，都是实的：
    ///   · 这两个命令行都在快速改版，参数写死在 C++ 里，它们一改就得重发
    ///     一个引擎；摆在配置里用户自己就能改。
    ///   · 写这段时手上只有 claude（2.1.272）能验，codex 没装——**没验过
    ///     的参数不该硬编进来冒充支持**。预设放在供应商清单里（那是数据，
    ///     改了不用重编），填错了也只是这一条后端不通。
    ///
    /// 提示词走**标准输入**，不走命令行参数：几万字塞不进去（Windows 上
    /// 整条命令行 32 KB 封顶），而 `claude -p` 的帮助里写的就是
    /// "useful for pipes"。见 proc::run 的 stdin_data。
    ///
    /// ⚠️ **这条路拿不到工具调用。** 「上网看热点写这一章」那一步要模型
    /// 会调工具（llm::Client::chat），命令行这条只有"一段字进、一段字出"。
    /// 那一步会照旧报"这个后端不支持工具"，不会假装成功。
    std::string command;
    /// 跑它的参数。空着就用 `command` 名字对应的那套预设（见 command.cpp）。
    std::vector<std::string> command_args;
    /// 一趟最多等多久。命令行那两个要自己起一个 agent 运行时，比直接打
