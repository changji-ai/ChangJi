#pragma once

// 接外来的活之前那道门。**纯逻辑，不含网络代码**，所以能测。
//
// 要挡的是这么一件事：`--worker` 现在那几条路由**一个鉴权都没有**，
// 而它一旦 `--host 0.0.0.0` 就在公网上了。谁都能派任务过来烧这张卡，
// 谁都能读 `/status` 看这台机器有什么模型。同机多卡时这不是问题
// （监听 127.0.0.1，外面连不进来），跨机就是。
//
// 规矩两条，都按"安全的那边"定：
//
//   一，**只在对外监听时要口令**。本机自己按显卡数拉起的那些工作进程
//       监听回环，不受影响——多卡那条路一行配置都不用改。
//   二，**没设口令就不许对外监听**，当场拒绝启动并说清楚怎么办。
//       反过来（没口令就放行）是最坏的默认值：它在"能跑"和"安全"之间
//       选了能跑，而出事时没有任何征兆。

#include <string>

namespace changji::infer {

/// 这个监听地址算不算"对外"。
///
/// 认不出来的一律算对外——**猜错的方向要挑代价小的那个**：
/// 把回环误判成对外，症状是"你得设个口令"；反过来是门开着没人知道。
bool is_public_bind(const std::string& host);

/// 该不该拒绝起这个服务。**回空串表示可以起。**
///
/// 回的那句话是直接打给用户看的，所以要说到"该怎么办"那一步。
std::string refuse_to_listen(const std::string& host, const std::string& token);

/// 请求带的口令对不对。
///
/// `expected` 为空一律 false——**没设口令 = 不接外来的活**，
/// 而不是"谁都能接"。
///
/// 只认 `Authorization: Bearer <口令>`（Bearer 大小写不敏感）。
/// 比较是**定长时间**的：这套东西是自己人之间用的，时序攻击几乎不可能，
/// 但常量时间比较的代价是零，没有理由不做。
bool token_ok(const std::string& auth_header, const std::string& expected);

/// 这个地址指的是不是本机（`http://127.0.0.1:9001` 这种）。
///
/// **派活时靠它决定文件搬不搬。** 同一台机器就是同一个文件系统：
/// 参考图直接给路径、产物直接写过去，一个字节都不用搬。跨机才走 blob。
///
/// 认不出的一律算跨机——猜错的方向同样挑代价小的那个：把同机误判成跨机
/// 是多传几 MB，反过来是对面拿着一个不存在的路径去读，那一镜直接失败。
bool endpoint_is_local(const std::string& url);

/// 从 `Authorization: Bearer xxx` 里把那串抠出来。抠不出回空串。
///
/// **给局域网那条路用的**：那头拿票当口令发过来，而票对不对要去问
/// `lan::Sense`（那是另一层，不能进这个文件——这儿是纯的）。
std::string bearer_of(const std::string& auth_header);

}  // namespace changji::infer
